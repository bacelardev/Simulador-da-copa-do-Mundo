export function getOrCreateConfronto(teamAId: string, teamBId: string, teamAName: string, teamBName: string): ConfrontoDirect {
  // Try to find exact match
  const match = HISTORIC_CONFRONTOS.find(
    (c) =>
      (c.teamAId === teamAId && c.teamBId === teamBId) ||
      (c.teamAId === teamBId && c.teamBId === teamAId)
  );

  if (match) {
    // Return order matching input parameter if reversed
    if (match.teamAId === teamBId) {
      return {
        teamAId,
        teamBId,
        matchesPlayed: match.matchesPlayed,
        winsA: match.winsB,
        winsB: match.winsA,
        draws: match.draws,
        goalsA: match.goalsB,
        goalsB: match.goalsA,
        memorableMatches: match.memorableMatches.map((m) => {
          // reverse scores if visible
          const scoreParts = m.score.split(' x ');
          let newScore = m.score;
          if (scoreParts.length === 2) {
            const leftTeamPart = scoreParts[0].substring(0, scoreParts[0].lastIndexOf(' '));
            const rightTeamPart = scoreParts[1].substring(scoreParts[1].indexOf(' ') + 1);
            const scoreNumLeft = scoreParts[0].substring(scoreParts[0].lastIndexOf(' ') + 1);
            const scoreNumRight = scoreParts[1].substring(0, scoreParts[1].indexOf(' '));
            newScore = `${rightTeamPart} ${scoreNumRight} x ${scoreNumLeft} ${leftTeamPart}`;
          }
          return { ...m, score: newScore };
        })
      };
    }
    return match;
  }

  // Generate plausible deterministic mock statistics based on team IDs to ensure continuity
  // Calculate a deterministic seed from team selection
  const combinedStr = [teamAId, teamBId].sort().join('-');
  let hash = 0;
  for (let i = 0; i < combinedStr.length; i++) {
    hash = combinedStr.charCodeAt(i) + ((hash << 5) - hash);
  }
  hash = Math.abs(hash);

  const matchesPlayed = 4 + (hash % 15); // 4 to 18 matches
  const draws = Math.floor((hash % 4) * (matchesPlayed / 10)); // realistic draws
  const remaining = matchesPlayed - draws;
  
  // Decide who is slightly better based on string lengths or ratings (simulated balance)
  const winsA = Math.floor(remaining / 2) + (hash % 2 === 0 ? Math.floor(hash % 3) : -Math.floor(hash % 2));
  const winsB = Math.max(0, remaining - winsA);
  const actualWinsA = Math.min(remaining, Math.max(0, winsA));
  const actualWinsB = remaining - actualWinsA;

  const avgGoals = 1.2 + ((hash % 10) / 10); // 1.2 to 2.2 average goals per match
  const goalsA = Math.round(actualWinsA * avgGoals + draws * 0.8 + (hash % 5));
  const goalsB = Math.round(actualWinsB * avgGoals + draws * 0.8 + ((hash + 3) % 5));

  const stages = ['Fase de Grupos da Copa', 'Amistoso Internacional', 'Oitavas de Final de Copa', 'Quartas de Final de Copa'];
  const stage = stages[hash % stages.length];
  const year = 1954 + (hash % 17) * 4; // realistic world cup years

  const isWinA = actualWinsA > actualWinsB;
  const scoreString = isWinA 
    ? `${teamAName} 2 x 1 ${teamBName}` 
    : actualWinsB > actualWinsA 
      ? `${teamAName} 0 x 2 ${teamBName}` 
      : `${teamAName} 1 x 1 ${teamBName}`;

  return {
    teamAId,
    teamBId,
    matchesPlayed,
    winsA: actualWinsA,
    winsB: actualWinsB,
    draws,
    goalsA,
    goalsB,
    memorableMatches: [
      {
        year,
        stage,
        score: scoreString,
        details: `Confronto disputado pelo torneio mundial de ${year}. Uma partida de muita intensidade tática que ajudou a moldar a rivalidade técnica entre ${teamAName} e ${teamBName}.`
      }
    ]
  };
}
